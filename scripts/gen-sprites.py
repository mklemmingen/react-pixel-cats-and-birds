#!/usr/bin/env python3
"""Regenerate src/sprites.js from the files in sprites/cats and sprites/birds."""
import os

root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
cats = sorted(f[:-4] for f in os.listdir(os.path.join(root, 'sprites/cats')) if f.endswith('.png'))
birds = sorted(f[:-4] for f in os.listdir(os.path.join(root, 'sprites/birds')) if f.endswith('.png'))


def camel(s):
    p = s.split('-')
    return p[0] + ''.join(x.capitalize() for x in p[1:])


out = [
    "/*",
    " * Sprite sheet URLs.",
    " *",
    " * Art: \"Cats || Pixel Asset Pack\" and \"Garden Birds || Pixel Asset Pack\" by Pop Shop Packs",
    " * https://pop-shop-packs.itch.io/ - used with the artist's permission, NOT covered by the MIT",
    " * licence of this package's code. See CREDITS.md.",
    " *",
    " * `new URL(..., import.meta.url)` with literal paths lets Vite, webpack 5, Next.js and",
    " * Parcel copy only these files into the build and rewrite the URLs.",
    " * Generated by scripts/gen-sprites.py - do not edit by hand.",
    " */",
    "",
    "/** cat colour variant -> sprite sheet URL */",
    "export const CAT_SHEETS = {",
]
out += [f"    '{c}': new URL('../sprites/cats/{c}.png', import.meta.url).href," for c in cats]
out += ["};", "", "/** bird species id -> sprite sheet URL */", "export const BIRD_SHEETS = {"]
out += [f"    {camel(b)}: new URL('../sprites/birds/{b}.png', import.meta.url).href," for b in birds]
out += ["};", "", "export const CAT_COLORS = Object.keys(CAT_SHEETS);",
        "export const BIRD_SPECIES = Object.keys(BIRD_SHEETS);", ""]

with open(os.path.join(root, 'src/sprites.js'), 'w') as f:
    f.write("\n".join(out))
